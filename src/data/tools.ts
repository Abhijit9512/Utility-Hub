export function getToolBySlug(category: string, slug: string) {
  return tools.find(t => t.category === category && t.slug === slug);
}
export function getToolsByCategory(cat: string) {
  return tools.filter(t => t.category === cat);
}
export function getRelatedTools(tool: ToolDefinition) {
  if (tool.relatedTools?.length) {
    return tools.filter(t => tool.relatedTools!.includes(t.id));
  }
  return tools.filter(t => t.category === tool.category && t.id !== tool.id).slice(0,4);
}